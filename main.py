"""Interactive CLI for the AI Study & Grade Advisor."""

from __future__ import annotations

from ai_advisor import analyze_performance, generate_ai_advice


def prompt_score(subject: str) -> float:
    """Prompt until a valid numeric score (0-100) is entered."""
    while True:
        raw = input(f"  Score for {subject} (0-100): ").strip()
        try:
            value = float(raw)
        except ValueError:
            print("  Invalid number. Please enter a score between 0 and 100.")
            continue
        if 0 <= value <= 100:
            return value
        print("  Score must be between 0 and 100.")


def main() -> None:
    """Run the AI Study & Grade Advisor CLI."""
    print("=== AI Study & Grade Advisor (Module 05) ===")
    name = input("Enter student name: ").strip()
    if not name:
        print("Student name cannot be empty.")
        return

    scores: dict[str, float] = {}
    print("Enter subjects and scores (leave subject blank when done):")
    while True:
        subject = input("  Subject name: ").strip()
        if not subject:
            break
        scores[subject] = prompt_score(subject)

    if not scores:
        print("No scores entered. Exiting.")
        return

    analysis = analyze_performance(name, scores)
    advice, source = generate_ai_advice(analysis)

    print("\n" + "=" * 56)
    print(advice)
    print("=" * 56)
    print(f"[Generated by: {source}]")


if __name__ == "__main__":
    main()
